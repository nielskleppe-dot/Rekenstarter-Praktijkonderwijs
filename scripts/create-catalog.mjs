function describeTask(label,t) {
  return [
    "#### "+label,
    "",
    "**Vraag**  "+t.question,
    "**Gegevens**  "+(t.facts.map(f=>f.label+" = "+f.value).join("; ")||"Lees de gegevens in het rekenmodel."),
    "**Stappen**",
    ...t.steps.map((step,i)=>(i+1)+". "+step),
    "**Antwoord**  "+t.answer,
    "**Eerste hint**  "+t.hint,
    "**Rekenmodel**  "+JSON.stringify(t.model||t.visual||{kind:"werkbon"}),
    ""
  ].join("\n");
}
